SETTINGS = Settings(kms_keyring="vl", google_cloud_project="p", google_cloud_location="asia-south1")


def test_kms_key_ids_are_valid_and_distinct() -> None:
    ids = {
        kms_key_id("vendor", k)
        for k in ["vendor:maya", "vendor_maya", "label-checker@host:retailer-svc", "x" * 90]
    }
    assert len(ids) == 4
    assert all(len(i) <= 63 and all(c.isalnum() or c in "-_" for c in i) for i in ids)
    assert kms_key_id("gateway", "gw") == "gateway-gw"


async def test_kms_signs_with_ed25519_that_verifies(no_sleep: None) -> None:
    fake = FakeKms()
    signer = KmsSigner(SETTINGS, "vendor", client=fake)
    assert signer.keyring == "projects/p/locations/asia-south1/keyRings/vl"
    public = await signer.public_key("vendor:maya")
    assert len(public) == 32
    signature = await signer.sign("vendor:maya", b"order-mandate")
    assert verify_signature(public, b"order-mandate", signature)
    assert fake.calls.count("create_crypto_key") == 1  # created once, reused
    other = await KmsSigner(SETTINGS, "retailer", client=fake).public_key("vendor:maya")
    assert other != public  # tenants never share keys


async def test_kms_rotation_is_staged_then_promoted_and_survives_restart(no_sleep: None) -> None:
    fake = FakeKms()
    signer = KmsSigner(SETTINGS, "vendor", client=fake)
    old = await signer.public_key("guardian")
    new = await signer.public_key("guardian#next")
    assert new != old
    assert await signer.public_key("guardian#next") == new  # staging is idempotent
    # until promoted, the old key still signs, also after a restart
    restarted = KmsSigner(SETTINGS, "vendor", client=fake)
    assert verify_signature(old, b"m", await restarted.sign("guardian", b"m"))
    await signer.promote("guardian#next", "guardian")
    assert await signer.public_key("guardian") == new
    assert verify_signature(
        new, b"m", await KmsSigner(SETTINGS, "vendor", client=fake).sign("guardian", b"m")
    )
    states = [v.state for v in next(iter(fake.keys.values()))]
    assert states == ["DISABLED", "ENABLED"]
    with pytest.raises(ValueError):
        await signer.promote("other", "guardian")


