# ---------------------------------------------------------------- GCS


class FakeBlob:
    def __init__(self, store: dict[str, tuple[bytes, str]], name: str) -> None:
        self.store, self.name = store, name

    def upload_from_string(self, data: bytes, content_type: str) -> None:
        self.store[self.name] = (data, content_type)

    def download_as_bytes(self) -> bytes:
        return self.store[self.name][0]


class FakeStorage:
    def __init__(self) -> None:
        self.objects: dict[str, tuple[bytes, str]] = {}
        self.buckets: list[str] = []

    def bucket(self, name: str) -> Any:
        self.buckets.append(name)
        objects = self.objects

        class Bucket:
            def blob(self, blob_name: str) -> FakeBlob:
                return FakeBlob(objects, blob_name)

        return Bucket()


async def test_gcs_blob_round_trip_and_stays_in_its_bucket() -> None:
    fake = FakeStorage()
    store = GcsBlobStore(Settings(gcs_bucket="vl-docs"), client=fake)
    uri = await store.put("vendor/maya/photo.png", b"\x89PNG", "image/png")
    assert uri == "gs://vl-docs/vendor/maya/photo.png"
    assert fake.objects["vendor/maya/photo.png"] == (b"\x89PNG", "image/png")
    assert await store.get(uri) == b"\x89PNG"
    with pytest.raises(ValueError):
        await store.get("gs://someone-else/vendor/maya/photo.png")
    with pytest.raises(ValueError):
        await store.put("../escape", b"", "text/plain")
    with pytest.raises(ValueError):
        GcsBlobStore(Settings(gcs_bucket=""), client=fake)


# ---------------------------------------------------------------- KMS


@dataclass
class Version:
    name: str
    state: str
    key: Ed25519PrivateKey = field(default_factory=Ed25519PrivateKey.generate)


class NotFound(Exception):  # the name google.api_core.exceptions uses for a 404
    pass


class FakeKms:
    """Just enough of KeyManagementServiceAsyncClient. New versions start PENDING_GENERATION."""

    def __init__(self) -> None:
        self.keys: dict[str, list[Version]] = {}
        self.calls: list[str] = []

    def _find(self, name: str) -> Version:
        key_name = name.split("/cryptoKeyVersions/")[0]
        return next(v for v in self.keys[key_name] if v.name == name)

    def _add_version(self, key_name: str) -> Version:
        version = Version(
            f"{key_name}/cryptoKeyVersions/{len(self.keys[key_name]) + 1}", "PENDING_GENERATION"
        )
        self.keys[key_name].append(version)
        return version

    async def create_crypto_key(self, request: dict[str, Any]) -> None:
        self.calls.append("create_crypto_key")
        name = f"{request['parent']}/cryptoKeys/{request['crypto_key_id']}"
        assert request["crypto_key"]["version_template"]["algorithm"] == "EC_SIGN_ED25519"
        if name in self.keys:
            raise RuntimeError("409 already exists")
        self.keys[name] = []
        self._add_version(name)

    async def create_crypto_key_version(self, request: dict[str, Any]) -> Version:
        self.calls.append("create_crypto_key_version")
        return self._add_version(request["parent"])

    async def get_crypto_key_version(self, request: dict[str, Any]) -> Version:
        version = self._find(request["name"])
        if version.state == "PENDING_GENERATION":
            version.state = "ENABLED"  # generated by the time anyone asks twice
            return Version(version.name, "PENDING_GENERATION", version.key)
        return version

    async def list_crypto_key_versions(self, request: dict[str, Any]) -> AsyncIterator[Version]:
        assert request["filter"] == "state=ENABLED"
        if request["parent"] not in self.keys:
            raise NotFound(f"404 CryptoKey {request['parent']} not found.")
        found = [v for v in self.keys[request["parent"]] if v.state == "ENABLED"]

        async def pager() -> AsyncIterator[Version]:
            for v in found:
                yield v

        return pager()

    async def asymmetric_sign(self, request: dict[str, Any]) -> Any:
        version = self._find(request["name"])
        assert version.state == "ENABLED"
        return type("R", (), {"signature": version.key.sign(request["data"])})()

    async def get_public_key(self, request: dict[str, Any]) -> Any:
        pem = (
            self._find(request["name"])
            .key.public_key()
            .public_bytes(
                serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
            )
        )
        return type("R", (), {"pem": pem.decode()})()

    async def update_crypto_key_version(self, request: dict[str, Any]) -> None:
        assert request["update_mask"] == {"paths": ["state"]}
        self._find(request["crypto_key_version"]["name"]).state = request["crypto_key_version"][
            "state"
        ]


