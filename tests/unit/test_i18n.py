import json
from pathlib import Path

import pytest

from tests.conftest import CONFIG_DIR
from vl_core.i18n import Strings, is_affirmative, is_negative
from vl_core.schemas import ReasonCode

LANGS = ["en", "te", "id"]


def keys(node: object, prefix: str = "") -> set[str]:
    if isinstance(node, dict):
        return set().union(*(keys(v, f"{prefix}{k}.") for k, v in node.items()))
    return {prefix.rstrip(".")}


def test_every_language_has_the_same_keys() -> None:
    base = keys(json.loads((CONFIG_DIR / "i18n" / "en.json").read_text()))
    for lang in LANGS:
        assert keys(json.loads((CONFIG_DIR / "i18n" / f"{lang}.json").read_text())) == base, lang


@pytest.mark.parametrize("lang", LANGS)
def test_every_reason_code_has_wording(lang: str) -> None:
    s = Strings(lang, CONFIG_DIR / "i18n")
    for code in ReasonCode:
        assert s.t(f"reasons.{code.value}")


@pytest.mark.parametrize(
    ("lang", "text", "yes"),
    [
        ("en", "Yes, go ahead", True),
        ("en", "no", False),
        ("en", "yes... no wait", False),
        ("en", "yesterday", False),
        ("te", "అవును", True),
        ("te", "సరే, చేయండి", True),
        ("te", "వద్దు", False),
        ("id", "Ya, setuju", True),
        ("id", "tidak", False),
        ("id", "dayak", False),
        ("en", "", False),
    ],
)
def test_affirmatives(lang: str, text: str, yes: bool) -> None:
    s = Strings(lang, CONFIG_DIR / "i18n")
    assert is_affirmative(text, s) is yes


def test_render_keeps_unknown_placeholders(tmp_path: Path) -> None:
    s = Strings("en", CONFIG_DIR / "i18n")
    assert "{allowed}" in s.t("reasons.QTY_OVER_DAILY_MAX", requested=350, sku="spinach")
    assert is_negative("no thanks", s)


def test_web_copies_are_current() -> None:
    """web/src/i18n is generated by scripts/export_schemas.py; it must not drift."""
    web = CONFIG_DIR.parent / "web" / "src" / "i18n"
    for path in (CONFIG_DIR / "i18n").glob("*.json"):
        copy = web / path.name
        assert copy.exists() and copy.read_text() == path.read_text(), (
            f"{copy} is stale: run `make schemas`"
        )
